-- Everyone on the LCR member list (imported from the Prayers tab)
create table if not exists ward_members (
  id          uuid primary key default gen_random_uuid(),
  import_key  text not null unique,              -- "Last, First Middle|birth date"
  last        text not null,
  first       text not null,                     -- given names from LCR
  goes_by     text not null default '',          -- what people call them, e.g. "Jim"
  gender      text not null default '',
  birth_date  date,
  phone       text not null default '',
  email       text not null default '',
  flags       text not null default '',          -- e.g. "Not Baptized"
  household   text not null default '',          -- LCR household heading
  aliases     text not null default '',          -- names as written in Wardbullet, separated by |
  never_ask   boolean not null default false,
  note        text not null default '',
  active      boolean not null default true,
  updated_at  timestamptz not null default now()
);

-- Who spoke and prayed (from Wardbullet, plus the prayers you assign here)
create table if not exists sacrament_history (
  id          uuid primary key default gen_random_uuid(),
  date        date not null,
  kind        text not null check (kind in ('speaker', 'invocation', 'benediction')),
  name        text not null,                     -- as written in Wardbullet
  member_id   uuid references ward_members(id) on delete set null,
  visitor     boolean not null default false,    -- not in the ward (missionaries, stake leaders)
  created_at  timestamptz not null default now(),
  unique (date, kind, name)
);

-- Prayers you've asked people to give
create table if not exists prayer_asks (
  id             uuid primary key default gen_random_uuid(),
  date           date not null,
  slot           text not null check (slot in ('open', 'close')),
  member_id      uuid not null references ward_members(id) on delete cascade,
  status         text not null default 'asked' check (status in ('asked', 'yes', 'no', 'noreply')),
  asked_at       timestamptz not null default now(),
  answered_at    timestamptz,
  reminded_at    timestamptz,
  in_wardbullet  boolean not null default false,
  created_at     timestamptz not null default now()
);

-- Sundays without a ward sacrament meeting (stake or general conference)
create table if not exists sacrament_days (
  date        date primary key,
  no_meeting  boolean not null default true,
  note        text not null default ''
);

alter table ward_members      enable row level security;
alter table sacrament_history enable row level security;
alter table prayer_asks       enable row level security;
alter table sacrament_days    enable row level security;

